const CUSTOM_CONNECTORS_KEY = 'maria_custom_connectors';
const CONNECTOR_SUGGESTIONS_KEY = 'maria_connector_suggestions';

export function loadCustomConnectors(): PluginEntry[] {
  try {
    const raw = localStorage.getItem(CUSTOM_CONNECTORS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed)) return parsed;
    }
  } catch {}
  return [];
}

export function saveCustomConnectors(items: PluginEntry[]) {
  try {
    localStorage.setItem(CUSTOM_CONNECTORS_KEY, JSON.stringify(items));
  } catch {}
}

export function loadConnectorSuggestions(): boolean {
  try {
    const raw = localStorage.getItem(CONNECTOR_SUGGESTIONS_KEY);
    if (raw !== null) return raw === 'true';
  } catch {}
  return true;
}

export function saveConnectorSuggestions(enabled: boolean) {
  try {
    localStorage.setItem(CONNECTOR_SUGGESTIONS_KEY, String(enabled));
  } catch {}
}

export function getAllPlugins(customConnectors: PluginEntry[] = []): PluginEntry[] {
  return [...customConnectors, ...PLUGINS_CATALOG];
}

export function getPluginById(
  id: string,
  customConnectors: PluginEntry[] = []
): PluginEntry | undefined {
  return getAllPlugins(customConnectors).find((p) => p.id === id);
}
